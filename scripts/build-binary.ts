/**
 * Compiles qrup into standalone executables with the built client embedded.
 *
 *   bun scripts/build-binary.ts                                   # dist/qrup for this machine
 *   bun scripts/build-binary.ts bun-darwin-arm64 bun-linux-x64    # dist/qrup-darwin-arm64, …
 *
 * Run `vite build` first; the client is read from `dist/client`.
 */
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const distDir: string = path.resolve(import.meta.dirname, '..', 'dist');
const clientDir: string = path.join(distDir, 'client');
const entryPath: string = path.join(distDir, 'binary-entry.ts');

/** Paths of all files in `dir`, relative to it, with `/` separators. */
function listFiles(dir: string): string[] {
  return fs
    .readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter((relative: string): boolean => fs.statSync(path.join(dir, relative)).isFile())
    .map((relative: string): string => relative.split(path.sep).join('/'))
    .sort();
}

/**
 * Writes an entry that imports every client file with `type: 'file'`, which embeds it unchanged,
 * and starts the server with those files keyed by URL path.
 */
function writeEntry(files: readonly string[]): void {
  const imports = files.map(
    (file: string, index: number): string =>
      `import f${index} from './client/${file}' with { type: 'file' };`,
  );
  const entries = files.map((file: string, index: number): string => `  '/${file}': f${index},`);
  const source = [
    '// Generated by scripts/build-binary.ts.',
    "import { start } from '../server/start';",
    ...imports,
    '',
    'start({ embedded: {',
    ...entries,
    '} });',
    '',
  ].join('\n');
  fs.writeFileSync(entryPath, source);
}

function compile(target: string | undefined): void {
  const outfile = path.join(distDir, target ? `qrup-${target.replace(/^bun-/, '')}` : 'qrup');
  const args = ['build', '--compile', entryPath, '--outfile', outfile];
  if (target) args.push(`--target=${target}`);
  const result = spawnSync('bun', args, { stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

const files = listFiles(clientDir);
if (!files.includes('index.html')) {
  throw new Error(`No built client in ${clientDir}; run \`vite build\` first.`);
}
writeEntry(files);

const targets = process.argv.slice(2);
for (const target of targets.length > 0 ? targets : [undefined]) compile(target);
